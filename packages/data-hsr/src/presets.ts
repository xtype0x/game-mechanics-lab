import type { StatusDef, UnitDef } from "@gml/core";
import data from "./generated/presets.generated.json";

/**
 * One entry of a preset menu. `apply` is the unit that replaces the selected team slot (its team is forced to
 * "ally" and its id made unique in the team). Statuses the unit casts are merged into the project by id.
 * Unavailable presets keep `apply: null` and explain why in `reason`.
 */
export interface Preset {
  id: string;
  name: string;
  subtitle?: string;
  available: boolean;
  reason?: string;
  apply: UnitDef | null;
  /** Extra StatusDefs the unit needs; merged into the project's statuses by id (same id is replaced). */
  statuses?: StatusDef[];
  /** Approximations or caveats of the modelled kit (tooltip). */
  note?: string;
  /** Filter facets for large groups, e.g. { 屬性: "冰", 命途: "智識" }; the menu offers one dropdown per key. */
  facets?: Record<string, string>;
}

export interface PresetGroup {
  id: string;
  title: string;
  /** Where the data comes from (shown as small text). */
  source?: string;
  /** Short note under the title, e.g. "整理中". */
  note?: string;
  presets: Preset[];
}

/** Generated by scripts/build-hsr-presets.mjs (data/reference/hsr/pack.json + docs/research/hsr-kit/catalog.json + kits). */
interface Generated {
  source: { text: string; version: string };
  presets: {
    id: string; name: string; subtitle?: string; available: boolean; reason?: string; note?: string;
    facets?: Record<string, string>; apply: unknown; statuses?: unknown[];
  }[];
}
const gen = data as unknown as Generated;

/** Every Star Rail character as a ready-to-use Lv80 unit (or the reason it is not available yet). */
export const hsrGroup: PresetGroup = {
  id: "hsr",
  title: "星穹鐵道",
  note: "社群資料・未核實",
  source: gen.source.text,
  presets: gen.presets.map((p): Preset => ({
    id: p.id,
    name: p.name,
    subtitle: p.subtitle,
    available: p.available,
    reason: p.reason,
    note: p.note,
    facets: p.facets,
    apply: p.apply as UnitDef | null,
    statuses: p.statuses as StatusDef[] | undefined,
  })),
};
